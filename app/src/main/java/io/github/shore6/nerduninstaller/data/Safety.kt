    fun classify(packageName: String, isSystem: Boolean): Safety {
        if (!isSystem) return Safety.USER
        return when {
            packageName in dangerExact -> Safety.DANGER
            dangerPrefixes.any { packageName.startsWith(it) } -> Safety.DANGER
            packageName in caution -> Safety.CAUTION
            packageName in recommended -> Safety.RECOMMENDED
            else -> Safety.UNKNOWN
        }
    }
