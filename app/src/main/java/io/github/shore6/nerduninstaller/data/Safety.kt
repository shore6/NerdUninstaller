/**
 * システムアプリを削除したときの危険度の目安。
 * あくまで一般的な目安で、端末・メーカーによって異なる場合がある。
 */
enum class Safety(val label: String, val description: String) {
    USER("ユーザー", "ユーザーがインストールしたアプリです。"),
    RECOMMENDED(
        "削除OK",
        "削除しても一般的にシステム動作に影響しないとされるプリインストールアプリです。",
    ),
    CAUTION(
        "注意",
        "削除すると一部の機能（通知・キーボード・ホーム画面・同期など）が使えなくなる可能性があります。代替アプリがある場合のみ削除してください。",
    ),
    DANGER(
        "危険",
        "システムの中核部品です。削除すると端末が正常に起動しなくなる（ブートループ）おそれがあります。削除しないでください。",
    ),
    UNKNOWN(
        "不明",
        "情報がないシステムアプリです。パッケージ名を調べてから削除するか、まずは「無効化」で様子を見ることをおすすめします。",
    ),
}

